package derpcraft.world;

/** A 16x256x16 column of 16 sections. */
public final class Chunk {
    public static final int HEIGHT = 256, SECTIONS = 16;
    public static final int STATE_NEW = 0, STATE_GENERATED = 1, STATE_LIT = 2;

    public final int cx, cz;
    public final Section[] sections = new Section[SECTIONS];
    /** Per column climate (0..255) used for grass/foliage colours. Index z*16+x. */
    public final byte[] temperature = new byte[256];
    public final byte[] humidity = new byte[256];
    public volatile int state = STATE_NEW;
    /** Needs saving. */
    public volatile boolean modified;
    /** When the chunk was read/generated by ChunkManager (to detect copies made stale by far-away edits). */
    public long loadStamp;
    /** Sequence number of the newest save written to disk (RegionStorage, guarded by its lock). */
    public long writtenSeq;
    /** Saves of this chunk queued or running (see ChunkManager.saveAsync). */
    public final java.util.concurrent.atomic.AtomicInteger saveRefs = new java.util.concurrent.atomic.AtomicInteger();
    /** Block entities keyed by {@link BlockEntityKey#key}. */
    public final java.util.Map<Integer, derpcraft.world.be.BlockEntity> blockEntities = new java.util.concurrent.ConcurrentHashMap<>();

    /** Per section: local indices of ENTITY-shaped blocks (chests, signs, beds), filled by the mesher. */
    public final int[][] entityBlocks = new int[SECTIONS][];

    public Chunk(int cx, int cz) { this.cx = cx; this.cz = cz; }

    /**
     * Map key of a chunk column (in-memory only: never decoded back to coordinates, never saved). The low half is cz
     * mixed with a hash of cx: with plain (cx << 32 | cz) Long.hashCode is cx ^ cz, so all chunks on one diagonal
     * collided (a 129x129 view had only ~256 different hashes) and every world.getState walked a tree bin.
     * Still one-to-one: cx is the high half, and cz is recovered by xoring the same mix of cx.
     */
    public static long key(int cx, int cz) {
        int m = cx * 0x9E3779B9;
        m ^= m >>> 16;
        return ((long) cx << 32) | ((cz ^ m) & 0xffffffffL);
    }
    public long key() { return key(cx, cz); }

    public int get(int x, int y, int z) {
        if (y < 0 || y >= HEIGHT) return 0;
        Section s = sections[y >> 4];
        return s == null ? 0 : s.get(Section.index(x, y & 15, z));
    }

    /** Raw set without lighting or notifications. Creates sections as needed. */
    public void setRaw(int x, int y, int z, int state) {
        if (y < 0 || y >= HEIGHT) return;
        Section s = sections[y >> 4];
        if (s == null) {
            if (state == 0) return;
            s = ensureSection(y >> 4);
        }
        s.set(Section.index(x, y & 15, z), state);
    }

    /** Sets a state without light or neighbour updates (World.setBlock adds those; WorldEdit relights in bulk).
     *  A replaced block takes its soot with it. */
    public void setEdited(int x, int y, int z, int state) {
        if (y < 0 || y >= HEIGHT) return;
        int old = get(x, y, z);
        setRaw(x, y, z, state);
        Section s = sections[y >> 4];
        if ((old >> 4) != (state >> 4) && s != null && s.soot != null) s.soot[Section.index(x, y & 15, z)] = 0;
    }

    /** Creates the section and any missing sections below it (so light storage is continuous). */
    public synchronized Section ensureSection(int sy) {
        for (int i = 0; i <= sy; i++) {
            if (sections[i] == null) {
                Section n = new Section();
                n.skyDefault = 15;
                sections[i] = n;
            }
        }
        return sections[sy];
    }

    /** Index of the highest section that contains blocks, or -1. */
    public int topSection() {
        for (int i = SECTIONS - 1; i >= 0; i--) if (sections[i] != null && !sections[i].isEmpty()) return i;
        return -1;
    }

    /** Highest non-air y in this column (or -1). */
    public int height(int x, int z) {
        for (int sy = topSection(); sy >= 0; sy--) {
            Section s = sections[sy];
            if (s == null || s.isEmpty()) continue;
            for (int y = 15; y >= 0; y--) if (s.get(Section.index(x, y, z)) != 0) return sy * 16 + y;
        }
        return -1;
    }

    public int getSky(int x, int y, int z) {
        if (y >= HEIGHT) return 15;
        if (y < 0) return 0;
        Section s = sections[y >> 4];
        return s == null ? 15 : s.getSky(Section.index(x, y & 15, z));
    }

    public int getLight(int x, int y, int z) {
        if (y < 0 || y >= HEIGHT) return 0;
        Section s = sections[y >> 4];
        return s == null ? 0 : s.getLight(Section.index(x, y & 15, z));
    }

    public int getLight(int ch, int x, int y, int z) {
        if (y < 0 || y >= HEIGHT) return 0;
        Section s = sections[y >> 4];
        return s == null ? 0 : s.getLight(ch, Section.index(x, y & 15, z));
    }
}
